#!/usr/bin/env python3
"""Writes the access review (Joint Standard 2 of 2024, access and privileged access): which service may call which
method of which service, and which staff role may do what in the back office. Generated from the caller allow-lists
and the back-office routes, so it shows what is enforced, not what someone remembers. A reviewer signs it each quarter
(docs/regulatory/policies/access-control-policy.md). Run: python3 -I scripts/access-review.py [out.md]"""
import glob, json, os, re, sys, datetime
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = []
w = out.append
w(f"# Access review, generated {datetime.date.today().isoformat()}\n")
w("Generated by `scripts/access-review.py` from what the code enforces. Review every line: remove what is not needed.\n")
w("## Service to service (mutual TLS identity, `deploy/compose/config/callers/`)\n")
w("| Callee | Caller | Methods | Writes? |\n|---|---|---|---|")
WRITE = re.compile(r"^(Create|Post|Void|Open|Decide|Approve|Set|Add|Record|Register|Start|Classify|Deposit|Withdraw|Draw|Repay|Accept|Apply|Cancel|Refund|Simulate|Close|Resolve|Investigate|Grant|Revoke|Ensure|Update|Delete|Book|Quote|Payout)")
total = writes = 0
for f in sorted(glob.glob(os.path.join(root, "deploy/compose/config/callers/*.json"))):
    callee = os.path.basename(f)[:-5]
    for caller, methods in sorted(json.load(open(f)).items()):
        wm = [m for m in methods if WRITE.match(m)]
        total += len(methods); writes += len(wm)
        w(f"| {callee} | {caller} | {', '.join(methods)} | {'yes: ' + ', '.join(wm) if wm else 'read only'} |")
w(f"\n{total} grants, {writes} of them able to change something.\n")
w("## Staff roles (back office, `services/shared/backoffice-api/internal/api/api.go`)\n")
api = open(os.path.join(root, "services/shared/backoffice-api/internal/api/api.go")).read()
roles = {}
for method, path, role in re.findall(r'mux\.HandleFunc\("(\w+) ([^"]+)", a\.staff\(needRole\((Role\w+)', api):
    roles.setdefault(role.replace("Role", "").lower(), []).append(f"{method} {path}")
for role in sorted(roles):
    w(f"- **{role}**: " + "; ".join(roles[role]))
w("- **any staff role**: every other back-office route, which only reads.\n")
w("Staff are granted roles in the identity provider (WorkOS), not here. That list of people and their roles is the")
w("other half of this review, and must be exported from the provider once it exists.\n")
w("## Sign-off\n\nReviewer: ________  Date: ________  Changes requested: ________\n")
text = "\n".join(out)
dest = sys.argv[1] if len(sys.argv) > 1 else None
if dest:
    open(dest, "w").write(text)
    print(f"access review: {total} service grants ({writes} writing), {sum(map(len, roles.values()))} role-gated routes -> {dest}")
else:
    print(text)
