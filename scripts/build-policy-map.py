#!/usr/bin/env python3
"""Builds docs/governance/POLICY_MAP.md: every draft policy placed under the Prudential Authority's structure (docs/governance/pa-framework.csv).

The PA has announced seven prudential standards for mutual banks (governance and risk management, operational risk, credit risk, liquidity
risk, IRRBB, capital, economic returns) but has not published them; the other areas are instruments already in force. `--check` fails if
the map is stale, a framework area names a policy file that does not exist, or a policy in policies.csv sits under no area.
"""
import csv, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GOV = os.path.join(ROOT, "docs/governance")
POL = os.path.join(ROOT, "docs/regulatory/policies")
def rows(p): return list(csv.DictReader(open(p, newline="")))
areas, pols = rows(os.path.join(GOV, "pa-framework.csv")), rows(os.path.join(GOV, "policies.csv"))
titles = {p["file"]: p["title"] for p in pols}
problems, used = [], set()
out = ["# Policies mapped to the Prudential Authority's structure", "",
       "> Generated by `scripts/build-policy-map.py` from [`pa-framework.csv`](pa-framework.csv) and [`policies.csv`](policies.csv). Every policy is",
       "> a DRAFT. **Announced** areas follow the seven prudential standards for mutual banks that the PA says it has developed but has not",
       "> published (PA annual reports 2024/25 and 2025/26): when they are published, each policy in that area must be checked against the text.",
       "> **Published** areas cite instruments already in force.", "",
       "| Area | Regulator's instruments | Status | Policies |", "|---|---|---|---|"]
for a in areas:
    files = [f for f in a["policies"].split(";") if f]
    for f in files:
        if not os.path.exists(os.path.join(POL, f)): problems.append(f"{a['id']}: no policy file {f}")
        used.add(f)
    links = "<br>".join(f"[{titles.get(f, f)}](../regulatory/policies/{f})" for f in files) or "**GAP: no policy**"
    out.append(f"| **{a['id']}** {a['area']} | {a['instruments']} | {a['status']} | {links} |")
for p in pols:
    if p["file"] not in used: problems.append(f"{p['file']} is under no PA area")
out += ["", f"{len(areas)} areas; {len(pols)} policies, each under at least one area."]
text = "\n".join(out) + "\n"
path = os.path.join(GOV, "POLICY_MAP.md")
if "--check" in sys.argv:
    if not os.path.exists(path) or open(path).read() != text: problems.append("POLICY_MAP.md is stale; run python3 -I scripts/build-policy-map.py")
else:
    open(path, "w").write(text)
for p in problems: print("FAIL", p)
if problems: sys.exit(1)
print(f"policy map: {len(areas)} PA areas, {len(pols)} policies mapped")
