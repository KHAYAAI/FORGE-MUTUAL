// Command returns-proforma builds pro forma returns (licence application, LIC-11) from projected ledger balances.
//
//	returns-proforma -form mutual -in projection.json -out proforma.md
//
// The projection lists periods, each with the projected net balance (credits less debits, rand cents) per ledger
// account code. The same specs that build live returns from the ledger build the pro formas, so the two cannot drift.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/khayaai/forge-mutual/services/bank/reg-reporting/internal/returns"
)

type projection struct {
	Note    string `json:"note"`
	Periods []struct {
		Period string           `json:"period"`
		Nets   map[string]int64 `json:"nets"`
	} `json:"periods"`
}

func main() {
	form := flag.String("form", "mutual", "mutual or bank")
	in := flag.String("in", "", "projection JSON")
	out := flag.String("out", "", "Markdown output (stdout if empty)")
	flag.Parse()
	if err := run(returns.LegalForm(*form), *in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "returns-proforma:", err)
		os.Exit(1)
	}
}

func run(form returns.LegalForm, in, out string) error {
	raw, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	var p projection
	if err := json.Unmarshal(raw, &p); err != nil {
		return err
	}
	var b strings.Builder
	refs := "this repository's own until mapped to the form instructions (VERIFY-FORMS)"
	if form == returns.Mutual {
		refs = "the form's own line numbers, transcribed from the PA's published forms (docs/regulatory/returns/SOURCES.md); a second person must check the transcription"
	}
	fmt.Fprintf(&b, "# Pro forma returns: %s route\n\n> Generated by `returns-proforma` from `%s`. PROJECTED figures, not actuals. Line references are\n> %s.\n\n%s\n\n", form, in, refs, p.Note)
	for _, period := range p.Periods {
		var ps []returns.Position
		nets := map[uint32]int64{}
		for k, v := range period.Nets {
			codeStr, product, _ := strings.Cut(k, "/")
			c, err := strconv.ParseUint(codeStr, 10, 32)
			if err != nil {
				return fmt.Errorf("%s: bad account code %q", period.Period, k)
			}
			nets[uint32(c)] += v
			ps = append(ps, returns.Position{Asset: "ZAR", Code: uint32(c), Product: product, Net: returns.Cents(v)})
		}
		if form == returns.Mutual {
			if err := mutual(&b, period.Period, ps); err != nil {
				return err
			}
			continue
		}
		bs, err := returns.BalanceSheet(form)
		if err != nil {
			return err
		}
		is, _ := returns.IncomeStatement(form)
		inputs, unmapped := returns.Inputs(nets)
		if len(unmapped) > 0 {
			return fmt.Errorf("%s: account codes not on any statement: %v", period.Period, unmapped)
		}
		for _, s := range []returns.Spec{bs, is} {
			r, err := s.Compute(period.Period, inputs, time.Now())
			if err != nil {
				return err
			}
			if len(r.Breaks) > 0 {
				return fmt.Errorf("%s %s does not balance: %s", period.Period, s.Form, strings.Join(r.Breaks, "; "))
			}
			b.WriteString(returns.Table(s, r) + "\n")
		}
	}
	if out == "" {
		_, err = os.Stdout.WriteString(b.String())
		return err
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// mutual writes DI 100 and DI 200 on the form's own lines. A projection runs from inception, so retained income at the start
// of the period is zero and DI 100 line 32 must equal DI 200 line 66.
func mutual(b *strings.Builder, period string, ps []returns.Position) error {
	in, problems := returns.DIInputs(ps, 0)
	if len(problems) > 0 {
		return fmt.Errorf("%s: %s", period, strings.Join(problems, "; "))
	}
	s100, err := returns.DI100()
	if err != nil {
		return err
	}
	s200, err := returns.DI200()
	if err != nil {
		return err
	}
	var results []returns.Result
	for _, s := range []returns.Spec{s100, s200} {
		r, err := s.Compute(period, in, time.Now())
		if err != nil {
			return err
		}
		if len(r.Breaks) > 0 {
			return fmt.Errorf("%s %s does not balance: %s", period, s.Form, strings.Join(r.Breaks, "; "))
		}
		results = append(results, r)
		b.WriteString(returns.FormTable(s, r) + "\n")
	}
	if br := returns.CrossCheck(results[0], results[1]); br != "" {
		return fmt.Errorf("%s: %s", period, br)
	}
	return nil
}
